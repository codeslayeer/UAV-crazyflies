"""Export benchmark results to CSV and LaTeX for reports."""

from __future__ import annotations

import csv
from pathlib import Path

from core.types import AggregatedMetrics, TrialRecord


def export_trials_csv(records: list[TrialRecord], filepath: str | Path) -> None:
    """
    Export raw per-trial results to CSV.

    One row per planner run — useful for statistical analysis or plotting
    error bars in external tools (Excel, pandas, R).
    """
    path = Path(filepath)
    path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "planner",
        "trial",
        "success",
        "length_m",
        "num_waypoints",
        "smoothness",
        "max_curvature",
        "compute_time_ms",
        "nodes_explored",
    ]

    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for r in records:
            m = r.metrics
            writer.writerow(
                {
                    "planner": r.planner_name,
                    "trial": r.trial_index,
                    "success": int(r.result.success),
                    "length_m": f"{m.length:.4f}" if m else "",
                    "num_waypoints": m.num_waypoints if m else "",
                    "smoothness": f"{m.smoothness:.4f}" if m else "",
                    "max_curvature": f"{m.max_curvature:.4f}" if m else "",
                    "compute_time_ms": f"{r.result.compute_time * 1000:.2f}",
                    "nodes_explored": r.result.nodes_explored,
                }
            )


def export_summary_csv(summaries: list[AggregatedMetrics], filepath: str | Path) -> None:
    """
    Export aggregated mean ± std results to CSV.

    This file maps directly to LaTeX table rows via ``export_latex_table``.
    """
    path = Path(filepath)
    path.parent.mkdir(parents=True, exist_ok=True)

    fieldnames = [
        "planner",
        "num_trials",
        "success_rate",
        "length_mean",
        "length_std",
        "compute_time_ms_mean",
        "compute_time_ms_std",
        "nodes_mean",
        "nodes_std",
        "smoothness_mean",
        "smoothness_std",
        "max_curvature_mean",
        "max_curvature_std",
    ]

    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for s in summaries:
            writer.writerow(
                {
                    "planner": s.planner_name,
                    "num_trials": s.num_trials,
                    "success_rate": f"{s.success_rate:.4f}",
                    "length_mean": f"{s.length_mean:.4f}",
                    "length_std": f"{s.length_std:.4f}",
                    "compute_time_ms_mean": f"{s.compute_time_mean * 1000:.2f}",
                    "compute_time_ms_std": f"{s.compute_time_std * 1000:.2f}",
                    "nodes_mean": f"{s.nodes_mean:.1f}",
                    "nodes_std": f"{s.nodes_std:.1f}",
                    "smoothness_mean": f"{s.smoothness_mean:.4f}",
                    "smoothness_std": f"{s.smoothness_std:.4f}",
                    "max_curvature_mean": f"{s.max_curvature_mean:.4f}",
                    "max_curvature_std": f"{s.max_curvature_std:.4f}",
                }
            )


def _fmt_pm(mean: float, std: float, decimals: int = 2) -> str:
    """Format mean ± std for LaTeX math mode."""
    if std < 1e-9:
        return f"{mean:.{decimals}f}"
    return f"{mean:.{decimals}f} $\\pm$ {std:.{decimals}f}"


def export_latex_table(
    summaries: list[AggregatedMetrics],
    filepath: str | Path,
    caption: str = "Planner comparison on the default benchmark map.",
    label: str = "tab:planner_benchmark",
) -> None:
    """
    Write a ready-to-paste LaTeX table.

    Requires ``\\usepackage{booktabs}`` in your document preamble.
    """
    path = Path(filepath)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "% Auto-generated by metrics/export.py",
        "% Preamble: \\usepackage{booktabs}",
        "\\begin{table}[htbp]",
        "  \\centering",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        "  \\begin{tabular}{lrrrrr}",
        "    \\toprule",
        "    Planner & Success (\\%) & Length (m) & Time (ms) & Nodes & Smoothness (rad$^2$) \\\\",
        "    \\midrule",
    ]

    for s in summaries:
        row = " & ".join(
            [
                _escape_latex(s.planner_name),
                f"{s.success_rate * 100:.0f}",
                _fmt_pm(s.length_mean, s.length_std),
                _fmt_pm(s.compute_time_mean * 1000, s.compute_time_std * 1000, decimals=1),
                _fmt_pm(s.nodes_mean, s.nodes_std, decimals=0),
                _fmt_pm(s.smoothness_mean, s.smoothness_std),
            ]
        )
        lines.append(f"    {row} \\\\")

    lines.extend(
        [
            "    \\bottomrule",
            "  \\end{tabular}",
            "\\end{table}",
            "",
        ]
    )

    path.write_text("\n".join(lines), encoding="utf-8")


def _escape_latex(text: str) -> str:
    """Escape special characters in planner names (e.g. RRT*)."""
    return (
        text.replace("\\", "\\textbackslash{}")
        .replace("&", "\\&")
        .replace("%", "\\%")
        .replace("*", "$^*$")
    )
